#!/usr/bin/env node

/**
 * NarraView Build-Time Configuration Generator
 * 
 * Injects build-time constants into src/config/generated.ts.
 * This guarantees that React Native for Vega (Kepler/Hermes) runtime
 * has immediate, reliable access to configuration constants even when
 * process.env is not present in standalone device packages.
 */

const fs = require('fs');
const path = require('path');

const mode = (process.argv[2] || process.env.NODE_ENV || 'development').toLowerCase();
const isDev = mode === 'development' || mode === 'debug';

// Default authoritative deployment values
const DEFAULT_API_BASE_URL = 'https://vif7g6ez24.execute-api.eu-north-1.amazonaws.com/prod';
const DEFAULT_AWS_REGION = 'eu-north-1';
const DEFAULT_DEMO_VIEWER_ID = 'narraview-demo-viewer';

// Read env file if present
function parseEnvFile(filePath) {
  const env = {};
  if (fs.existsSync(filePath)) {
    const lines = fs.readFileSync(filePath, 'utf8').split('\n');
    for (const line of lines) {
      const trimmed = line.trim();
      if (trimmed && !trimmed.startsWith('#')) {
        const idx = trimmed.indexOf('=');
        if (idx > 0) {
          const key = trimmed.slice(0, idx).trim();
          const val = trimmed.slice(idx + 1).trim();
          env[key] = val;
        }
      }
    }
  }
  return env;
}

const rootDir = path.resolve(__dirname, '..');
const envFile = isDev
  ? path.join(rootDir, '.env.development')
  : path.join(rootDir, '.env.production');

const fileEnv = parseEnvFile(envFile);

const apiBaseUrl = process.env.NARRAVIEW_API_BASE_URL || fileEnv.NARRAVIEW_API_BASE_URL || DEFAULT_API_BASE_URL;
const awsRegion = process.env.NARRAVIEW_AWS_REGION || fileEnv.NARRAVIEW_AWS_REGION || DEFAULT_AWS_REGION;

// Strict Production Safety: Demo viewer ID is strictly null in production builds!
const demoViewerId = isDev
  ? (process.env.NARRAVIEW_DEMO_VIEWER_ID || fileEnv.NARRAVIEW_DEMO_VIEWER_ID || DEFAULT_DEMO_VIEWER_ID)
  : null;

// Telemetry (Safe - no secrets)
console.log('[NARRAVIEW_BUILD_CONFIG]', {
  mode: isDev ? 'development' : 'production',
  apiBaseUrl,
  awsRegion,
  demoViewerEnabled: Boolean(demoViewerId),
  demoViewerId: demoViewerId || '(disabled)'
});

const generatedContent = `// AUTO-GENERATED BY scripts/generate-config.js - DO NOT EDIT MANUALLY
export interface NarraViewGeneratedConfig {
  API_BASE_URL: string;
  AWS_REGION: string;
  DEMO_VIEWER_ID: string | null;
  BUILD_MODE: 'development' | 'production';
}

export const GENERATED_CONFIG: NarraViewGeneratedConfig = {
  API_BASE_URL: '${apiBaseUrl}',
  AWS_REGION: '${awsRegion}',
  DEMO_VIEWER_ID: ${demoViewerId ? `'${demoViewerId}'` : 'null'},
  BUILD_MODE: '${isDev ? 'development' : 'production'}'
};
`;

const outputPath = path.join(rootDir, 'src', 'config', 'generated.ts');
fs.writeFileSync(outputPath, generatedContent, 'utf8');
console.log(`[NARRAVIEW_BUILD_CONFIG] Wrote ${outputPath}`);
